"""Internal admin API for reviewing miscategorized expenses (issue #414).

Admin-only and never user-facing: the `/suggestions` flow (uncategorized
expenses) is a different feature and is not touched here. These endpoints are
the analyst interface of the detection pipeline while it is being validated.
"""

from datetime import datetime

from fastapi import APIRouter, Depends, HTTPException
from pydantic import BaseModel
from sqlalchemy.orm import Session, joinedload

from app.database import get_db
from app.models import CategorizationReview, User
from app.services import categorization_review as review_service
from app.services.auth import get_current_admin

router = APIRouter(prefix="/admin/categorization-reviews", tags=["admin"])


# ── Schemas ──────────────────────────────────────────────────────────


class ReviewItem(BaseModel):
    id: int
    expense_id: int
    user_id: int
    date: str | None = None
    description: str | None = None
    amount: float | None = None
    currency: str | None = None
    current_category_id: int | None = None
    current_category_name: str | None = None
    suggested_category_id: int | None = None
    suggested_category_name: str | None = None
    score: float
    source: str
    reason: str
    status: str
    detector_version: str
    created_at: str | None = None
    reviewed_at: str | None = None


class ReviewDetail(ReviewItem):
    evidence: dict = {}


class AcceptBody(BaseModel):
    category_id: int | None = None


class ScanBody(BaseModel):
    user_id: int | None = None
    since: str | None = None
    use_llm: bool = True
    persist: bool = True


# ── Serialization ────────────────────────────────────────────────────


def _iso(value: datetime | None) -> str | None:
    return value.isoformat() if value else None


def _serialize(review: CategorizationReview, with_evidence: bool = False) -> dict:
    expense = review.expense
    current = review.current_category
    suggested = review.suggested_category
    data = {
        "id": review.id,
        "expense_id": review.expense_id,
        "user_id": review.user_id,
        "date": expense.date.isoformat() if expense and expense.date else None,
        "description": expense.description if expense else None,
        "amount": expense.amount if expense else None,
        "currency": expense.currency if expense else None,
        "current_category_id": review.current_category_id,
        "current_category_name": current.name if current else None,
        "suggested_category_id": review.suggested_category_id,
        "suggested_category_name": suggested.name if suggested else None,
        "score": review.score,
        "source": review.source,
        "reason": review.reason,
        "status": review.status,
        "detector_version": review.detector_version,
        "created_at": _iso(review.created_at),
        "reviewed_at": _iso(review.reviewed_at),
    }
    if with_evidence:
        import json

        try:
            data["evidence"] = json.loads(review.evidence or "{}")
        except ValueError:
            data["evidence"] = {}
    return data


def _load(db: Session, review_id: int) -> CategorizationReview:
    review = (
        db.query(CategorizationReview)
        .options(
            joinedload(CategorizationReview.expense),
            joinedload(CategorizationReview.current_category),
            joinedload(CategorizationReview.suggested_category),
        )
        .filter(CategorizationReview.id == review_id)
        .first()
    )
    if review is None:
        raise HTTPException(status_code=404, detail="Revisión no encontrada")
    return review


# ── Endpoints ────────────────────────────────────────────────────────


@router.get(
    "",
    response_model=dict,
    summary="List miscategorization reviews",
    description=(
        "Return the internal reviews generated by the miscategorization detector, "
        "with the observed precision of the detector so far."
    ),
)
def list_reviews(
    status: str = "pending",
    user_id: int | None = None,
    min_score: float | None = None,
    signal: str | None = None,
    page: int = 1,
    per_page: int = 50,
    db: Session = Depends(get_db),
    admin: User = Depends(get_current_admin),
):
    """`status`: pending | accepted | rejected | investigated | all."""
    if page < 1 or per_page < 1 or per_page > 200:
        raise HTTPException(status_code=400, detail="paginación inválida")
    query = db.query(CategorizationReview).options(
        joinedload(CategorizationReview.expense),
        joinedload(CategorizationReview.current_category),
        joinedload(CategorizationReview.suggested_category),
    )
    if status != "all":
        query = query.filter(CategorizationReview.status == status)
    if user_id is not None:
        query = query.filter(CategorizationReview.user_id == user_id)
    if min_score is not None:
        query = query.filter(CategorizationReview.score >= min_score)

    rows = query.order_by(CategorizationReview.score.desc()).all()
    if signal:
        import json

        def has_signal(row: CategorizationReview) -> bool:
            try:
                evidence = json.loads(row.evidence or "{}")
            except ValueError:
                return False
            return signal in (evidence.get("signals") or {})

        rows = [row for row in rows if has_signal(row)]

    total = len(rows)
    start = (page - 1) * per_page
    items = [_serialize(row) for row in rows[start : start + per_page]]
    return {
        "items": items,
        "total": total,
        "page": page,
        "per_page": per_page,
        "summary": review_service.summary(db, user_id=user_id),
    }


@router.get(
    "/{review_id}",
    response_model=ReviewDetail,
    summary="Get one review with its evidence",
    description="Return the review plus the signals and LLM verdict behind the score.",
)
def get_review_detail(
    review_id: int,
    db: Session = Depends(get_db),
    admin: User = Depends(get_current_admin),
):
    review = _load(db, review_id)
    return ReviewDetail(**_serialize(review, with_evidence=True))


@router.post(
    "/{review_id}/accept",
    summary="Accept a review and apply the category",
    description=(
        "Apply the suggested category (or an explicit one) to the expense, teach "
        "the merchant preference and mark the review as accepted."
    ),
)
def accept(
    review_id: int,
    body: AcceptBody | None = None,
    db: Session = Depends(get_db),
    admin: User = Depends(get_current_admin),
):
    category_id = body.category_id if body else None
    try:
        review = review_service.accept_review(
            db, review_id, category_id=category_id, reviewer_id=admin.id
        )
    except review_service.ReviewNotFoundError as e:
        raise HTTPException(status_code=404, detail=str(e))
    except review_service.StaleReviewError as e:
        raise HTTPException(status_code=409, detail=str(e))
    except review_service.MissingCategoryError as e:
        raise HTTPException(status_code=400, detail=str(e))
    return _serialize(_load(db, review.id), with_evidence=True)


@router.post(
    "/{review_id}/reject",
    summary="Reject a review",
    description="Mark the review as a false positive; the expense keeps its category.",
)
def reject(
    review_id: int,
    db: Session = Depends(get_db),
    admin: User = Depends(get_current_admin),
):
    try:
        review = review_service.reject_review(db, review_id, reviewer_id=admin.id)
    except review_service.ReviewNotFoundError as e:
        raise HTTPException(status_code=404, detail=str(e))
    return _serialize(_load(db, review.id), with_evidence=True)


@router.post(
    "/{review_id}/investigate",
    summary="Mark a review as investigated",
    description="Mark the review as looked at without changing the expense.",
)
def investigate(
    review_id: int,
    db: Session = Depends(get_db),
    admin: User = Depends(get_current_admin),
):
    try:
        review = review_service.investigate_review(db, review_id, reviewer_id=admin.id)
    except review_service.ReviewNotFoundError as e:
        raise HTTPException(status_code=404, detail=str(e))
    return _serialize(_load(db, review.id), with_evidence=True)


@router.post(
    "/scan",
    summary="Run the detector now",
    description=(
        "Review the expenses created since the given date (forward-only; defaults to "
        "the last 7 days) and persist the findings. Same code path as the daily job."
    ),
)
def scan(
    body: ScanBody | None = None,
    db: Session = Depends(get_db),
    admin: User = Depends(get_current_admin),
):
    body = body or ScanBody()
    since = None
    if body.since:
        try:
            since = datetime.fromisoformat(body.since)
        except ValueError:
            raise HTTPException(status_code=400, detail="since debe ser ISO 8601")

    user_ids = [body.user_id] if body.user_id else None
    result = review_service.scan_users(
        db,
        user_ids=user_ids,
        since=since,
        use_llm=body.use_llm,
        persist=body.persist,
    )
    return result
